/**
 * Fastify app factory for the API gateway.
 * Registers security headers, CORS, request-id, metrics, and all route groups.
 */
import Fastify, { FastifyInstance } from 'fastify';
import cors from '@fastify/cors';
import helmet from '@fastify/helmet';
import { prisma } from '@api-website/db';
import { Jwt } from '@api-website/auth';
import type { GatewayConfig } from './config.js';
import { Metrics } from './lib/metrics.js';
import { AuthMiddleware } from './lib/authMiddleware.js';
import { RateLimiter } from './lib/rateLimit.js';
import { registerAuthRoutes } from './routes/auth.routes.js';
import { registerKeyRoutes } from './routes/keys.routes.js';
import { registerUsageRoutes } from './routes/usage.routes.js';
import { registerAdminRoutes } from './routes/admin.routes.js';
import { registerBusinessRoutes } from './routes/business.routes.js';

export interface BuiltApp {
  app: FastifyInstance;
  rateLimiter: RateLimiter;
}

export async function buildApp(cfg: GatewayConfig): Promise<BuiltApp> {
  const app = Fastify({
    logger: {
      level: process.env.NODE_ENV === 'production' ? 'warn' : 'info',
      transport:
        process.env.NODE_ENV === 'production'
          ? undefined
          : { target: 'pino-pretty', options: { colorize: false } },
    },
  });

  // Security headers.
  await app.register(helmet, { global: true });

  // CORS — allow-list driven by env; '*' when ALLOWED_ORIGINS is unset.
  const origins = cfg.allowedOrigins.includes('*') ? true : cfg.allowedOrigins;
  await app.register(cors, { origin: origins, methods: ['GET', 'POST', 'PATCH', 'DELETE', 'OPTIONS'], credentials: true });

  // JSON body parsing (Fastify does this by default; explicit for clarity).
  // Request id is generated by Fastify built-in (request.id) — exposed in meta.

  // Shared services.
  const jwt = new Jwt({ secret: cfg.jwtSecret, accessTtl: cfg.accessTtl, refreshTtl: cfg.refreshTtl });
  const auth = new AuthMiddleware(jwt);
  const rateLimiter = new RateLimiter(cfg);
  const metrics = new Metrics();
  app.metrics = metrics; // module-augmented FastifyInstance

  // Health check (DB + rate-limiter backend).
  app.get('/health', async (_req, reply) => {
    let db = 'ok';
    try {
      await prisma.$queryRaw`SELECT 1`;
    } catch {
      db = 'unreachable';
    }
    const status = db === 'ok' ? 200 : 503;
    return reply.code(status).send({
      status: db === 'ok' ? 'ok' : 'degraded',
      db,
      rateLimitBackend: rateLimiter.backend,
      uptimeSec: Math.round(process.uptime()),
    });
  });

  // Prometheus scrape endpoint.
  app.get('/metrics', async (_req, reply) => {
    reply.header('Content-Type', 'text/plain; version=0.0.4');
    return reply.send(metrics.render());
  });

  // Route groups.
  registerAuthRoutes(app, { jwt });
  registerKeyRoutes(app, { auth });
  registerUsageRoutes(app, { auth });
  registerAdminRoutes(app, { auth });
  registerBusinessRoutes(app, { auth, rateLimiter });

  // 404 in the unified envelope.
  app.setNotFoundHandler((_req, reply) => {
    reply.code(404).send({ success: false, data: null, error: 'Route not found', meta: {} });
  });

  // Global error handler.
  app.setErrorHandler((error, _req, reply) => {
    console.error('[gateway] unhandled error', error);
    reply.code(500).send({ success: false, data: null, error: 'Internal server error', meta: {} });
  });

  await app.ready();
  return { app, rateLimiter };
}